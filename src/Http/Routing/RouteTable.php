<?php

declare(strict_types=1);

namespace Mailadmin\Http\Routing;

/**
 * The compiled route table, as written to `var/cache/routes.php`.
 *
 * It carries two checksums (U-8):
 *
 *  - `specChecksum` — SHA-256 of the bundled specification the routes were
 *    compiled from. Compared at startup; a mismatch means somebody shipped a
 *    contract and a route table that do not belong together.
 *  - `sourceChecksum` — fingerprint of the contract *sources*. Only development
 *    looks at it, to notice that a partial was edited and rebuild before the
 *    next request rather than after the next deployment.
 */
final readonly class RouteTable
{
    /**
     * @param list<Route> $routes
     */
    public function __construct(
        public string $specChecksum,
        public string $sourceChecksum,
        public string $basePath,
        public array $routes,
        public string $generatedAt,
    ) {
    }

    /**
     * @return array<string, mixed>
     */
    public function toArray(): array
    {
        return [
            'spec_checksum' => $this->specChecksum,
            'source_checksum' => $this->sourceChecksum,
            'base_path' => $this->basePath,
            'generated_at' => $this->generatedAt,
            'routes' => array_map(static fn (Route $route): array => $route->toArray(), $this->routes),
        ];
    }

    /**
     * @param array<string, mixed> $data
     *
     * @throws StaleBuildError if the file is not the shape this class writes
     */
    public static function fromArray(array $data): self
    {
        foreach (['spec_checksum', 'source_checksum', 'base_path', 'generated_at'] as $key) {
            if (!is_string($data[$key] ?? null)) {
                throw StaleBuildError::unreadable(sprintf('the compiled route table (missing "%s")', $key));
            }
        }

        if (!is_array($data['routes'] ?? null)) {
            throw StaleBuildError::unreadable('the compiled route table (missing "routes")');
        }

        $routes = [];

        /** @var mixed $route */
        foreach ($data['routes'] as $route) {
            if (!is_array($route)) {
                throw StaleBuildError::unreadable('the compiled route table (a route is not a mapping)');
            }

            /** @var array<string, mixed> $route */
            $routes[] = Route::fromArray($route);
        }

        /** @var array{spec_checksum: string, source_checksum: string, base_path: string, generated_at: string} $data */

        return new self(
            specChecksum: $data['spec_checksum'],
            sourceChecksum: $data['source_checksum'],
            basePath: $data['base_path'],
            routes: $routes,
            generatedAt: $data['generated_at'],
        );
    }

    /**
     * A `var_export`ed PHP file, not JSON: opcache keeps it compiled in memory,
     * so reading the route table on a warm process costs an `include` and no
     * parsing at all.
     */
    public function toPhpSource(): string
    {
        return "<?php\n\n"
            . "declare(strict_types=1);\n\n"
            . "// Generated by bin/compile-routes.php from the bundled OpenAPI contract.\n"
            . "// Do not edit: the next \"composer build\" overwrites it, and the checksums\n"
            . "// below are what keeps a stale copy from being served (U-8).\n\n"
            . 'return ' . var_export($this->toArray(), true) . ";\n";
    }
}

<?php

declare(strict_types=1);

namespace Mailadmin\Domain\Sieve;

use Mailadmin\Domain\Exception\InvalidSieveRule;

/**
 * Renders a rule set into a complete Sieve script — generate, never patch
 * (architecture 9.4).
 *
 * The output is deterministic: the same rule set always produces the same
 * bytes. That matters twice over — an ETag (U-19) stays stable, and a diff in
 * the audit trail shows what actually changed.
 *
 * Order of the parts is not cosmetic:
 *
 *  1. `require` — Sieve demands it before any command.
 *  2. filters, which may end in `stop;`, so that a message filed into a folder
 *     does not also trigger an out-of-office reply;
 *  3. redirects, with an explicit `keep;` when the mailbox should keep a copy —
 *     `redirect` cancels the implicit keep;
 *  4. `vacation` last, because it neither cancels the keep nor consumes the
 *     message.
 *
 * Line endings are CRLF (RFC 5228). Nothing here reads an existing script. What
 * is ever read back is the marker and the model line under it
 * ({@see SieveRuleSetCodec}, U-102) — never the Sieve itself — and
 * `SieveScript` does that.
 */
final readonly class SieveRenderer
{
    public const string EOL = "\r\n";

    private const string INDENT = '    ';

    /**
     * @throws InvalidSieveRule
     */
    public function render(SieveRuleSet $rules, string $name = SieveScript::LEGACY_NAME): SieveScript
    {
        return SieveScript::of($name, $this->renderContent($rules));
    }

    public function renderContent(SieveRuleSet $rules): string
    {
        $lines = [
            SieveScript::markerLine(),
            // The rule set as data, so that the next change starts from the
            // model and not from the script (U-102). Directly under the marker:
            // that is the only place SieveRuleSetCodec::modelOf() looks.
            SieveRuleSetCodec::MODEL_PREFIX . SieveRuleSetCodec::encode($rules),
            '# Generated by mailadmin from the stored rule set.',
            '# Manual changes are lost the next time a rule changes.',
        ];

        $extensions = $rules->requiredExtensions();

        if ($extensions !== []) {
            $lines[] = '';
            $lines[] = 'require [' . implode(', ', array_map(
                static fn (string $extension): string => self::quote($extension),
                $extensions,
            )) . '];';
        }

        foreach ($rules->filters() as $filter) {
            $lines[] = '';

            foreach ($this->renderFilter($filter) as $line) {
                $lines[] = $line;
            }
        }

        if ($rules->hasRedirects()) {
            $lines[] = '';

            foreach ($rules->redirects() as $redirect) {
                $lines[] = 'redirect ' . self::quote($redirect->destination->toString()) . ';';
            }

            if ($rules->keepsLocalCopy()) {
                // redirect cancels the implicit keep — without this line the
                // message would only leave the system, never stay.
                $lines[] = 'keep;';
            }
        }

        $vacation = $rules->vacation();

        if ($vacation !== null) {
            $lines[] = '';

            foreach ($this->renderVacation($vacation) as $line) {
                $lines[] = $line;
            }
        }

        return implode(self::EOL, $lines) . self::EOL;
    }

    /**
     * @return list<string>
     */
    private function renderFilter(FilterRule $filter): array
    {
        $tests = [];

        foreach ($filter->conditions as $condition) {
            $tests[] = sprintf(
                'header %s %s %s',
                $condition->matchType->value,
                self::quote($condition->header),
                self::quote($condition->value),
            );
        }

        $test = count($tests) === 1
            ? $tests[0]
            : $filter->join->value . ' (' . implode(', ', $tests) . ')';

        $lines = ['if ' . $test . ' {'];

        $lines[] = self::INDENT . match ($filter->action) {
            FilterAction::FileInto => 'fileinto ' . self::quote((string) $filter->folder) . ';',
            FilterAction::Discard => 'discard;',
            FilterAction::Keep => 'keep;',
        };

        if ($filter->stopAfterMatch) {
            $lines[] = self::INDENT . 'stop;';
        }

        $lines[] = '}';

        return $lines;
    }

    /**
     * @return list<string>
     */
    private function renderVacation(VacationRule $vacation): array
    {
        $command = 'vacation :days ' . $vacation->intervalDays;

        if ($vacation->subject !== null) {
            $command .= ' :subject ' . self::quote($vacation->subject);
        }

        $addresses = $vacation->addressStrings();

        if ($addresses !== []) {
            $command .= ' :addresses [' . implode(', ', array_map(
                static fn (string $address): string => self::quote($address),
                $addresses,
            )) . ']';
        }

        // A multi-line literal, not a quoted string: the message carries
        // newlines, quotation marks and umlauts, and must survive all three.
        $lines = [$command . ' text:'];

        foreach ($this->messageLines($vacation->message) as $line) {
            $lines[] = $line;
        }

        $lines[] = '.';
        $lines[] = ';';

        return $lines;
    }

    /**
     * The message body, split into lines and dot-stuffed: a line starting with
     * `.` would otherwise end the literal early (RFC 5228, section 8.1).
     *
     * @return list<string>
     */
    private function messageLines(string $message): array
    {
        $split = preg_split('/\r\n|\r|\n/', $message);

        if ($split === false) {
            $split = [$message];
        }

        $lines = [];

        foreach ($split as $line) {
            $lines[] = str_starts_with($line, '.') ? '.' . $line : $line;
        }

        return $lines;
    }

    /**
     * A Sieve quoted string: backslash and quotation mark are escaped, nothing
     * else is touched.
     */
    private static function quote(string $value): string
    {
        return '"' . str_replace(['\\', '"'], ['\\\\', '\\"'], $value) . '"';
    }
}
